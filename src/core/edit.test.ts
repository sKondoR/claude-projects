import { describe, expect, it } from 'vitest';
import { closeCard, doneNote, moveCard } from './edit';

const SRC = `# Задачи

## Сайт

### С1 · Первая

**Приоритет:** Высокая · **Риск:** 1

Текст первой.

### С2 · Вторая

**Приоритет:** Низкая · **Риск:** 0

## Карты

### Л1 · Третья

**Приоритет:** Средняя · **Риск:** 0
`;

describe('moveCard', () => {
	it('вставляет блок в конец раздела с тем же именем', () => {
		const dst = '# Бэклог\n\n## Сайт\n\n### С9 · Старая\n\n**Приоритет:** Низкая · **Риск:** 0\n\n## Другое\n\n### Д1 · X\n';
		const r = moveCard(SRC, dst, 'С1');
		expect(r?.src).toBe(
			'# Задачи\n\n## Сайт\n\n### С2 · Вторая\n\n**Приоритет:** Низкая · **Риск:** 0\n\n## Карты\n\n### Л1 · Третья\n\n**Приоритет:** Средняя · **Риск:** 0\n',
		);
		expect(r?.dst).toBe(
			'# Бэклог\n\n## Сайт\n\n### С9 · Старая\n\n**Приоритет:** Низкая · **Риск:** 0\n\n### С1 · Первая\n\n**Приоритет:** Высокая · **Риск:** 1\n\nТекст первой.\n\n## Другое\n\n### Д1 · X\n',
		);
	});

	it('создаёт раздел в конце файла, если его нет', () => {
		const r = moveCard(SRC, '# Бэклог\n', 'Л1');
		expect(r?.dst).toBe('# Бэклог\n\n## Карты\n\n### Л1 · Третья\n\n**Приоритет:** Средняя · **Риск:** 0\n');
		expect(r?.src.endsWith('**Приоритет:** Низкая · **Риск:** 0\n\n## Карты\n')).toBe(true);
	});

	it('вставляет в последний раздел файла', () => {
		const r = moveCard(SRC, '# Б\n\n## Карты\n\n### Л0 · A\n', 'Л1');
		expect(r?.dst).toBe('# Б\n\n## Карты\n\n### Л0 · A\n\n### Л1 · Третья\n\n**Приоритет:** Средняя · **Риск:** 0\n');
	});

	it('сохраняет переводы строк каждого файла', () => {
		const r = moveCard(SRC.replace(/\n/g, '\r\n'), '# Б\n', 'С2');
		expect(r?.src).toContain('\r\n');
		expect(r?.src).not.toMatch(/[^\r]\n/);
		expect(r?.dst).not.toContain('\r');
	});

	it('переносит блок кода с заголовками целиком', () => {
		const card = '### К1 · Код\n\n**Риск:** 0\n\n```bash\n# установка\n## шаг\n```\n\nКонец.';
		const r = moveCard(`# З\n\n## Р\n\n${card}\n\n### К2 · Другая\n`, '# Б\n', 'К1');
		expect(r?.src).toBe('# З\n\n## Р\n\n### К2 · Другая\n');
		expect(r?.dst).toBe(`# Б\n\n## Р\n\n${card}\n`);
	});

	it('не вставляет блок внутрь блока кода в разделе назначения', () => {
		const dst = '# Б\n\n## Сайт\n\n### С9 · Старая\n\n```\n# комментарий\n```\n';
		const r = moveCard(SRC, dst, 'С2');
		expect(r?.dst).toBe(`${dst}\n### С2 · Вторая\n\n**Приоритет:** Низкая · **Риск:** 0\n`);
	});

	it('возвращает null, если задачи нет', () => {
		expect(moveCard(SRC, '', 'Х1')).toBeNull();
	});
});

describe('closeCard', () => {
	it('переносит блок в конец файла закрытых и пишет строку под полями', () => {
		const done = '# Закрытые задачи\n\n### С0 · Давняя\n\n**Приоритет:** Низкая · **Риск:** 0\n**Сделано:** 01.11.2026\n';
		const r = closeCard(SRC, done, 'С1', '**Сделано:** 19.11.2026, отмечено на доске');
		expect(r?.dst).toBe(
			done + '\n### С1 · Первая\n\n**Приоритет:** Высокая · **Риск:** 1\n**Сделано:** 19.11.2026, отмечено на доске\n\nТекст первой.\n',
		);
		expect(r?.src).not.toContain('С1');
	});

	it('строка закрытия: дата и PR', () => {
		expect(doneNote(new Date(2026, 0, 5))).toBe('**Сделано:** 05.01.2026, отмечено на доске');
		expect(doneNote(new Date(2026, 10, 19), 'https://github.com/x/y/pull/7')).toBe('**Сделано:** 19.11.2026, отмечено на доске, PR https://github.com/x/y/pull/7');
	});

	it('создаёт файл закрытых, если его нет', () => {
		const r = closeCard(SRC, '', 'С2', '**Сделано:** 19.11.2026');
		expect(r?.dst).toBe('# Закрытые задачи\n\n### С2 · Вторая\n\n**Приоритет:** Низкая · **Риск:** 0\n**Сделано:** 19.11.2026\n');
	});
});
