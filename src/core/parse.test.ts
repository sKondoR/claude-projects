import { describe, expect, it } from 'vitest';
import { ownerLabel } from './labels';
import { closedIdsOf, idsOf, parseGroup } from './parse';

const FILE = `# Задачи

## Новый сайт

Пояснение к разделу.

### С3 · Платёжный аккаунт

**Приоритет:** Высокая · **Трудность:** Лёгкая · **Риск:** 2 · **Зависит от:** С1, Л2 · **Ждёт этапа:** 1 · **Уточнить у владельца** · **Найдено:** 2026-11-18, план

Хостинг сайта работает в облаке владельца.

- Что сделать: завести аккаунт.

**Вопрос владельцу:** Можете завести аккаунт?
- Да, картой (рекомендуем)
- По счёту

## Прочее

### К1 · Без строки полей

Просто текст.
`;

describe('parseGroup', () => {
	const [card, bare] = parseGroup(FILE, 'issues');

	it('читает номер, заголовок, раздел и группу', () => {
		expect(card).toMatchObject({ id: 'С3', title: 'Платёжный аккаунт', section: 'Новый сайт', group: 'issues' });
		expect(bare).toMatchObject({ id: 'К1', section: 'Прочее' });
	});

	it('читает строку полей', () => {
		expect(card).toMatchObject({
			priority: 'Высокая',
			difficulty: 'Лёгкая',
			risk: '2',
			deps: ['С1', 'Л2'],
			stage: '1',
			found: '2026-11-18, план',
			owner: 'владельца',
		});
		expect(card?.warnings).toEqual([]);
	});

	it('выносит вопросы владельцу из подробностей', () => {
		expect(card?.questions).toEqual([
			{
				to: 'владельцу',
				text: 'Можете завести аккаунт?',
				options: [
					{ text: 'Да, картой', recommended: true },
					{ text: 'По счёту', recommended: false },
				],
			},
		]);
		expect(card?.body).toBe('Хостинг сайта работает в облаке владельца.\n\n- Что сделать: завести аккаунт.');
		expect(card?.questionsText).toBe('Можете завести аккаунт?\n- Да, картой (рекомендуем)\n- По счёту');
	});

	it('понимает «заказчика» и «юристу» вместо владельца', () => {
		const [c] = parseGroup(
			'### Ф7 · Госуслуги\n\n**Приоритет:** Средняя · **Риск:** 2 · **Уточнить у заказчика**\n\n**Вопрос юристу:** Можно?\n',
			'issues',
		);
		expect(c?.owner).toBe('заказчика');
		expect(c?.questions[0]?.to).toBe('юристу');
	});

	it('метка пометки в именительном падеже, незнакомое слово как есть', () => {
		expect(['владельца', 'заказчика', 'юриста', 'команды'].map(ownerLabel)).toEqual(['владелец', 'заказчик', 'юрист', 'команды']);
	});

	it('предупреждает об ошибках формата', () => {
		expect(bare?.warnings).toEqual(['нет строки полей под заголовком', 'нет поля «Риск»']);
		const [bad] = parseGroup('### Х1 · Т\n\n**Приоритет:** Низкая · **Риск:** 5\n', 'issues');
		expect(bad?.warnings).toEqual(['неизвестный риск «5»: должно быть 0, 1 или 2']);
	});

	it('понимает переводы строк Windows', () => {
		expect(parseGroup(FILE.replace(/\n/g, '\r\n'), 'issues')[0]?.risk).toBe('2');
	});

	it('заголовки в блоке кода — часть текста задачи', () => {
		const text = '## Р\n\n### А1 · X\n\n**Приоритет:** Низкая · **Риск:** 0\n\n```bash\n# установка\n## шаг\n```\n\nКонец.\n\n### А2 · Y\n';
		const cards = parseGroup(text, 'issues');
		expect(cards.map((c) => [c.id, c.section])).toEqual([
			['А1', 'Р'],
			['А2', 'Р'],
		]);
		expect(cards[0]?.body).toBe('```bash\n# установка\n## шаг\n```\n\nКонец.');
	});

	it('номера задач: заголовок в блоке кода — не задача', () => {
		expect(idsOf('### А1 · X\n\n```md\n### А9 · пример\n```\n\n### А2 · Y\n')).toEqual(['А1', 'А2']);
	});

	it('номера закрытых задач: заголовки и пункты старого формата «- [x] **У4 · …**»', () => {
		const text = '- [x] **У4 · Низкая · Старая задача** (найдено 2026-10-29).\n- [ ] **S28 · Средняя · Ещё одна**\n\n### Ш1 · Новая\n\n```md\n- [x] **А9 · пример**\n```\n';
		expect(closedIdsOf(text)).toEqual(['У4', 'S28', 'Ш1']);
		expect(idsOf(text)).toEqual(['Ш1']);
	});

	it('незакрытый блок кода не поглощает следующие задачи', () => {
		expect(parseGroup('### А1 · X\n\n```\n# a\n\n### А2 · Y\n', 'issues').map((c) => c.id)).toEqual(['А1', 'А2']);
	});
});
